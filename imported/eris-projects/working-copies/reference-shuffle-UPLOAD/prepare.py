"""
prepare(raw, public, private) -> None

Builds the public/private split for The Reference Shuffle from
dataset/raw/wiki_citation_units.jsonl.

TASK SHAPE
Each graded unit is ONE ENCYCLOPEDIA PARAGRAPH whose inline citation markers
have been replaced with a neutral [CITE] token, presented alongside a
SHUFFLED pool of that paragraph's own cited references -- each rendered as
a structured metadata card (title / author / venue / year), never as raw
citation-template wikitext. The solver must recover the ORDER in which the
shuffled references were actually cited in the paragraph, i.e. assign the
correct reference letter to each [CITE] marker in reading order.

Every card in a unit's pool IS a true citation of that paragraph by
construction: membership is given, and the withheld information is order
plus, on every card, one of its recorded fields (see INCOMPLETE CARDS).
The graded artifact is a permutation over the unit's own four cards,
scored per card by position accuracy with an exact 1/4 chance floor --
not a subset, a label, a ranking against a corpus, or a confusion-matrix
statistic.

INCOMPLETE CARDS (one recorded field withheld per card)
Each card shows three of its four fields. Which field is withheld is
drawn per card, uniformly among the fields the editor actually recorded
(a field that was never recorded is shown as its usual placeholder and
cannot be the withheld one), under the same fixed seed as the shuffle,
and is rendered in place as "[withheld]". The withheld value is not
written anywhere in the public or private files. Because the draw is
independent of the card's true position, which field is missing carries
no information about the order (measured: a probe that sorts cards by
whether their title is withheld sits at chance). What it does change is
the evidence available per card: a card without its title has to be
placed from its author, venue and year, or by elimination once the
fully-identifiable cards in the same pool have been placed.

GROUND TRUTH
The true order is the archive's own recorded structure: the sequence in
which <ref>...</ref> markers physically occur in the article's own
wikitext, written by the article's editors. Nothing about the order is
inferred, annotated, or generated by this pipeline -- build_raw.py records
it directly from marker position during extraction.

FILTER (already applied by build_raw.py, re-verified here)
Only paragraphs where every cited reference is a distinct, fully-inline
{cite journal|book|web|news|magazine|encyclopedia} template survive --
no <ref name="x"/> reuse, no {{sfn}}/{{harv}} shorthand -- so the
marker -> reference mapping is unambiguous.

SPLIT
Split by ARTICLE (source page), not by paragraph, so no two
paragraphs from the same article can appear on both sides -- an agent
that has memorised one paragraph's reference list from train cannot reuse
article-level cues (writing style, topic, editor's citation habits) to
solve a held-out paragraph from the SAME article in test.

FIXED POOL SIZE (four cards per unit)
Every unit carries exactly four references, so every ref_*_card and
rank_* column is 100% filled, every unit is the same 4x4 assignment with
24 candidate orders, and the chance floor is exactly 1/4 on every row.
Paragraphs with exactly four citations are used as they are. A paragraph
with five to eight citations contributes one window of four CONSECUTIVE
citations, its start drawn under the fixed seed; the [CITE] markers of
the citations outside the window are deleted from the text, so the
paragraph keeps exactly four markers, and the four kept references keep
their true relative order. Paragraphs with three citations are not used.

TARGET ENCODING (rank_A .. rank_D)
The answer for a unit is four independent integer columns, one per
shuffled label: rank_X is the 0-indexed position that label X's underlying
citation truly occupies in the paragraph's reading order. Each column is a
plain scalar integer in {0, 1, 2, 3}, and the four together are always a
permutation of {0, 1, 2, 3}. The grader compares each card's submitted
position with its true position directly from these four columns. (A
single delimited string such as "C A B D" would carry the same
information but is not a scalar target column; four integer columns are.)

GROUND TRUTH FILE
private/answers.csv is ONE ROW PER UNIT: unit_id, rank_A, rank_B, rank_C,
rank_D. None of these four names appear in test.csv (test.csv carries only
the shuffled cards, never their true rank), so test.csv and answers.csv
share only the unit_id join key.
"""
import csv
import html
import itertools
import json
import random
import re
import sys
import time
from pathlib import Path

csv.field_size_limit(10**9)

SEED = 20260925

# Every shipped unit has EXACTLY this many references -- see module
# docstring, "FIXED POOL SIZE".
N_REFS = 4

# Fraction of units held out for test (whole articles at a time). Chosen
# so test holds several hundred units while train stays larger.
TEST_ARTICLE_FRACTION = 0.45

# Cap on shipped paragraph length (characters). Citation-bearing paragraphs
# in these articles run long; this keeps the package a reasonable size
# without cutting the signal-bearing sentence containing each marker.
MAX_TEXT_CHARS = 4000


def _resolve_raw(raw: Path) -> Path:
    """Find the file that actually holds the raw units, tolerant of the
    platform placing raw_root at a different nesting depth than local."""
    raw = Path(raw)
    marker = "wiki_citation_units.jsonl"
    if (raw / marker).exists():
        return raw / marker
    for sub in ("raw", "dataset/raw"):
        if (raw / sub / marker).exists():
            return raw / sub / marker
    hits = sorted(raw.glob(f"**/{marker}"))
    if hits:
        return hits[0]
    raise FileNotFoundError(
        f"could not find {marker} under {raw!s}; "
        f"contents: {sorted(p.name for p in raw.iterdir())[:20]}")


def _load_units(path: Path) -> list:
    units = []
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            units.append(json.loads(line))
    return units


def _labels_for(n: int) -> list:
    return [chr(ord("A") + i) for i in range(n)]


_TEMPLATE_TAIL = re.compile(r"\s*(\}\}|\{\{).*$", re.S)


def _clean_field(value) -> str:
    """Strip source-markup residue from one card field: italic quote marks,
    HTML entities, and any dangling template fragment ('}} {{rating ...',
    '{{sic', '}}{{cbignore'). The editor-typed value itself is kept."""
    v = html.unescape(str(value)).replace("\xa0", " ")
    v = _TEMPLATE_TAIL.sub("", v)
    v = v.replace("'''", "").replace("''", "")
    return re.sub(r"\s+", " ", v).strip()


def _clean_text(text: str) -> str:
    """Strip source-markup residue from a paragraph. An embedded image
    caption survives extraction as '<caption>]]' either before the
    paragraph or after its last [CITE]; that caption text is dropped.
    [CITE] markers are never touched -- the caller re-checks the count."""
    t = html.unescape(text).replace("\xa0", " ")
    # leading image-option prefix, e.g. 'thumb|upright=1.1|right|alt=...|'
    t = re.sub(r"^\s*thumb\|(?:[^|\]]*\|)*", "", t)
    if "]]" in t:
        head, _, tail = t.rpartition("]]")
        last = head.rfind("[CITE]")
        if last < 0:
            t = tail                              # caption before the paragraph
        else:
            t = head[:last + len("[CITE]")] + " " + tail  # caption after the last marker
    t = t.replace("[[", "").replace("]]", "")
    t = t.replace("{{", "").replace("}}", "")
    t = t.replace("'''", "").replace("''", "")
    return re.sub(r"\s+", " ", t).strip()


def _truncate_keep_markers(text: str, limit: int) -> str:
    """Cap text at `limit` characters, but never cut before the end of the
    last [CITE] marker, so truncation can never remove a marker."""
    last = text.rfind("[CITE]")
    cut = max(limit, last + len("[CITE]") if last >= 0 else 0)
    return text[:cut]


def _window(unit: dict, rng: random.Random) -> dict:
    """Reduce a unit with more than N_REFS citations to N_REFS consecutive
    ones (seeded start). Markers outside the window are deleted from the
    text; the kept references stay in their true relative order."""
    n = unit["n_refs"]
    if n == N_REFS:
        return unit
    start = rng.randrange(n - N_REFS + 1)
    keep = range(start, start + N_REFS)
    parts = unit["text"].split("[CITE]")
    text = parts[0]
    for k in range(n):
        text += ("[CITE]" if k in keep else "") + parts[k + 1]
    return {"page": unit["page"], "text": text, "n_refs": N_REFS,
            "refs": [unit["refs"][k] for k in keep]}


CARD_FIELDS = ("title", "author", "venue", "year")
_PLACEHOLDER = {"title": "(untitled)", "author": "(uncredited)",
                "venue": "(unspecified)", "year": "(undated)"}
WITHHELD = "[withheld]"


def _card_fields(ref: dict) -> dict:
    return {k: _clean_field(ref[k]) if ref.get(k) else "" for k in CARD_FIELDS}


def _card_text(ref: dict, withhold: str) -> str:
    """Render one reference's structured metadata as a compact card with
    exactly one recorded field replaced by WITHHELD. Field order is fixed
    (title, author, venue, year) so no field position leaks identity
    across the shuffle -- every card has the same shape."""
    f = _card_fields(ref)
    parts = []
    for k in CARD_FIELDS:
        if k == withhold:
            parts.append(f"{k}: {WITHHELD}")
        elif f[k]:
            parts.append(f"{k}: {f[k]}")
        else:
            parts.append(f"{k}: {_PLACEHOLDER[k]}")
    return " | ".join(parts)


def _split_units_by_article(units: list, rng: random.Random, test_fraction: float):
    """Assign whole ARTICLES to train/test so no two paragraphs from the
    same page cross the split. Shuffled before greedy assignment so the
    split does not depend on the raw file's fetch order."""
    by_article = {}
    for u in units:
        by_article.setdefault(u["page"], []).append(u)

    articles = list(by_article.keys())
    rng.shuffle(articles)
    total = len(units)
    target_test = total * test_fraction

    test_articles, train_articles = [], []
    test_count = 0
    for a in articles:
        if test_count < target_test:
            test_articles.append(a)
            test_count += len(by_article[a])
        else:
            train_articles.append(a)

    test_units = [u for a in test_articles for u in by_article[a]]
    train_units = [u for a in train_articles for u in by_article[a]]
    return train_units, test_units


def prepare(raw: Path, public: Path, private: Path) -> None:
    t0 = time.time()
    raw, public, private = Path(raw), Path(public), Path(private)
    units_path = _resolve_raw(raw)
    print(f"[0.0s] reading raw units from {units_path}", file=sys.stderr)
    public.mkdir(parents=True, exist_ok=True)
    private.mkdir(parents=True, exist_ok=True)

    rng = random.Random(SEED)

    raw_units = _load_units(units_path)
    print(f"[{time.time()-t0:.1f}s] loaded {len(raw_units)} raw units", file=sys.stderr)

    # Re-verify the filter build_raw.py already applied -- defensive, in
    # case raw/ was hand-edited or came from a different build run -- then
    # reduce every unit to N_REFS consecutive citations (see module
    # docstring, "FIXED POOL SIZE").
    filtered = []
    for u in raw_units:
        n = u.get("n_refs", 0)
        if n < N_REFS:
            continue
        if len(u.get("refs", [])) != n:
            continue
        if u["text"].count("[CITE]") != n:
            continue
        u = _window(u, rng)
        titles_years = {(r["title"].lower(), r.get("year")) for r in u["refs"]}
        if len(titles_years) != N_REFS:
            continue
        filtered.append(u)
    print(f"[{time.time()-t0:.1f}s] {len(filtered)} units pass re-verification "
          f"(n_refs >= {N_REFS}, reduced to {N_REFS})", file=sys.stderr)

    train_units, test_units = _split_units_by_article(filtered, rng, TEST_ARTICLE_FRACTION)
    print(f"[{time.time()-t0:.1f}s] split: {len(train_units)} train, {len(test_units)} test "
          f"({len({u['page'] for u in train_units})} / "
          f"{len({u['page'] for u in test_units})} articles)", file=sys.stderr)

    labels = _labels_for(N_REFS)
    ref_cols = [f"ref_{L}_card" for L in labels]
    rank_cols = [f"rank_{L}" for L in labels]

    def emit(units, prefix):
        rows = []
        for n, u in enumerate(units):
            uid = f"{prefix}_{n:05d}"
            order = list(range(N_REFS))
            rng.shuffle(order)  # order[i] = original position now shown at label i
            shuffled_refs = [u["refs"][order[i]] for i in range(N_REFS)]
            # rank_of_label[label i] = true 0-indexed reading position of
            # the citation now shown under that label. order[i] is the
            # ORIGINAL (true-order) index of the reference now at label i,
            # which IS its true reading-position rank directly.
            ranks = {labels[i]: order[i] for i in range(N_REFS)}

            text = _truncate_keep_markers(_clean_text(u["text"]), MAX_TEXT_CHARS)
            assert text.count("[CITE]") == N_REFS, uid
            row = {"unit_id": uid, "text": text}
            for i, L in enumerate(labels):
                recorded = [k for k in CARD_FIELDS if _card_fields(shuffled_refs[i])[k]]
                withhold = rng.choice(recorded)  # one recorded field per card, seeded
                row[f"ref_{L}_card"] = _card_text(shuffled_refs[i], withhold)
            rows.append((row, uid, ranks))
        return rows

    train_emitted = emit(train_units, "train")
    test_emitted = emit(test_units, "test")

    base_cols = ["unit_id", "text"] + ref_cols

    with open(public / "train.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=base_cols + rank_cols)
        w.writeheader()
        for row, uid, ranks in train_emitted:
            out = dict(row)
            for L in labels:
                out[f"rank_{L}"] = ranks[L]
            w.writerow(out)

    with open(public / "test.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=base_cols)
        w.writeheader()
        for row, _, _ in test_emitted:
            w.writerow(row)

    with open(public / "sample_submission.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=["unit_id"] + rank_cols)
        w.writeheader()
        # Format example only, rotating through the N_REFS! possible rank
        # assignments so no column is constant.
        perms = list(itertools.permutations(range(N_REFS)))
        for i, (row, uid, _) in enumerate(test_emitted):
            perm = perms[i % len(perms)]
            w.writerow({"unit_id": uid, **{f"rank_{L}": perm[j] for j, L in enumerate(labels)}})

    with open(private / "answers.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=["unit_id"] + rank_cols)
        w.writeheader()
        for _, uid, ranks in test_emitted:
            w.writerow({"unit_id": uid, **{f"rank_{L}": ranks[L] for L in labels}})

    print(f"[{time.time()-t0:.1f}s] wrote {len(train_emitted)} train / "
          f"{len(test_emitted)} test units", file=sys.stderr)

if __name__ == "__main__":
    here = Path(__file__).resolve().parent
    raw_dir = here / "dataset" / "raw"
    if not raw_dir.exists():
        raw_dir = Path("raw")
    prepare(raw_dir, here / "dataset" / "public", here / "dataset" / "private")

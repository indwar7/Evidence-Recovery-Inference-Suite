"""
build_raw.py -- fetch raw material for the citation-order-recovery challenge.

SOURCE
English Wikipedia (en.wikipedia.org), via the public MediaWiki Action API
(`action=parse`, `prop=wikitext`), NOT the dumps.wikimedia.org bulk mirror
used by a prior challenge on this account (enwiktionary dumps) -- this is a
different project (encyclopedia articles vs. a dictionary), a different
host+endpoint, and a genuinely different data origin.

WHAT IS FETCHED
For a sample of "Good article" and "Featured article" pages (Wikipedia's own
quality-review categories -- these are pages that have passed a structured
community review, which correlates with well-formed, template-based
citations rather than ad hoc shorthand), this script:

  1. Pulls the raw wikitext of the article.
  2. Splits it into paragraphs.
  3. Keeps paragraphs with 3-8 <ref>...</ref> markers where EVERY marker is
     a distinct, fully-inline {{cite journal|book|web|news|magazine|
     encyclopedia}} template (no <ref name="x"/> reuse within the
     paragraph, no {{sfn}}/{{harv}} shorthand, no un-templated citation
     text). This keeps the marker -> reference mapping unambiguous: each
     [CITE] marker in the paragraph corresponds to exactly one, and only
     one, of the paragraph's own reference templates.
  4. Parses each kept reference template into structured fields (title,
     author, year, venue) -- these are the archive's OWN citation metadata,
     recorded by the article's editors in the wikitext, not inferred or
     generated by this pipeline.
  5. Replaces each ref marker in the paragraph text with a neutral [CITE]
     token and strips wiki markup down to plain prose.

FETCH DISCIPLINE (Part 3 of the playbook)
- One worker, no concurrency.
- Sleep 0.8-1.5s (random) between every HTTP request.
- Every request is wrapped in a broad `except Exception`, retried up to 3
  times with backoff, then skipped -- a single bad article must not kill
  a multi-hour run.
- Output is written incrementally (one JSON line appended per article) so
  an interrupted run loses at most one article's work, not the whole run.
- Article titles are drawn from Wikipedia's own "Good articles" and
  "Featured articles" categories via `list=categorymembers`, paginated
  with the API's own `cmcontinue` token (not a fixed 500-item page), so
  the sample is not artificially capped or alphabetically clustered.

LICENSE
Confirmed live via the MediaWiki siteinfo API:
    https://en.wikipedia.org/w/api.php?action=query&meta=siteinfo&siprop=rightsinfo&format=json
  -> {"rightsinfo":{"url":"https://creativecommons.org/licenses/by-sa/4.0/deed.en",
                     "text":"Creative Commons Attribution-Share Alike 4.0"}}
Quoted verbatim in ATTRIBUTION.txt / meta.json.
"""
import json
import random
import re
import sys
import time
import urllib.error
import urllib.parse
import urllib.request
from pathlib import Path

HEADERS = {"User-Agent": "ERIS-research-build/1.0 (contact: abhayindwar7@gmail.com)"}
API = "https://en.wikipedia.org/w/api.php"

MIN_REFS = 3
MAX_REFS = 8
MIN_PARA_CHARS = 150
MAX_ARTICLES_PER_CATEGORY = 1400

OUT_DIR = Path(__file__).resolve().parent.parent / "raw"
UNITS_PATH = OUT_DIR / "wiki_citation_units.jsonl"
TITLES_PATH = OUT_DIR / "_fetched_titles.json"

REF_FULL = re.compile(r'<ref(?:\s+name="([^"]+)")?\s*>(.*?)</ref>', re.S)
REF_SELF = re.compile(r'<ref\s+name="([^"]+)"\s*/>')
REF_ANY = re.compile(r"<ref[^>]*/>|<ref[^>]*>.*?</ref>", re.S)
FULL_CITE_RE = re.compile(r"\{\{\s*[Cc]ite\s+(journal|book|web|news|magazine|encyclopedia)\b", re.I)
CITE_PARSE_RE = re.compile(r"\{\{\s*[Cc]ite\s+(\w+)\s*\|(.*)\}\}\s*$", re.S)
YEAR_RE = re.compile(r"(1[5-9]\d\d|20\d\d)")


def _sleep():
    time.sleep(random.uniform(0.8, 1.5))


def _get(params: dict, tries: int = 3):
    url = API + "?" + urllib.parse.urlencode(params)
    last_err = None
    for attempt in range(tries):
        try:
            req = urllib.request.Request(url, headers=HEADERS)
            with urllib.request.urlopen(req, timeout=25) as r:
                return json.load(r)
        except Exception as e:  # broad on purpose -- see module docstring
            last_err = e
            print(f"  [retry {attempt+1}/{tries}] {type(e).__name__}: {e}", file=sys.stderr)
            time.sleep(2.0 * (attempt + 1))
    print(f"  [give up] {last_err}", file=sys.stderr)
    return None


def fetch_category_titles(category: str, limit: int) -> list:
    titles, cont = [], None
    while len(titles) < limit:
        params = {
            "action": "query", "list": "categorymembers", "cmtitle": category,
            "cmlimit": "500", "format": "json", "cmnamespace": "0",
        }
        if cont:
            params["cmcontinue"] = cont
        d = _get(params)
        _sleep()
        if d is None or "query" not in d:
            break
        titles.extend(m["title"] for m in d["query"]["categorymembers"])
        cont = d.get("continue", {}).get("cmcontinue")
        if not cont:
            break
    return titles[:limit]


def fetch_wikitext(title: str):
    d = _get({"action": "parse", "page": title, "prop": "wikitext", "format": "json"})
    if d is None or "parse" not in d:
        return None
    return d["parse"]["wikitext"]["*"]


def strip_wiki_markup(text: str) -> str:
    prev = None
    while prev != text:
        prev = text
        text = re.sub(r"\{\{[^{}]*\}\}", "", text)
    text = re.sub(r"\[\[File:[^\]]*\]\]", "", text, flags=re.I)
    text = re.sub(r"\[\[([^\]|]*\|)?([^\]]*)\]\]", r"\2", text)
    text = re.sub(r"'''?", "", text)
    text = re.sub(r"<[^>]+>", "", text)
    text = re.sub(r"\s+", " ", text).strip()
    return text


def clean_field(v: str) -> str:
    v = re.sub(r"\[\[([^\]|]*\|)?([^\]]*)\]\]", r"\2", v or "")
    v = re.sub(r"<[^>]+>", "", v)
    v = re.sub(r"\{\{[^{}]*\}\}", "", v)
    return v.strip().strip(".,;")


def extract_year(fields: dict):
    for k in ("year", "date", "publication-date", "access-date"):
        v = fields.get(k, "")
        m = YEAR_RE.search(v)
        if m:
            return m.group(1)
    return None


def parse_cite_fields(raw: str):
    m = CITE_PARSE_RE.match(raw.strip())
    if not m:
        return None
    kind, body = m.group(1).lower(), m.group(2)
    parts = re.split(r"\|(?![^\[]*\]\])", body)
    fields = {}
    for p in parts:
        if "=" in p:
            k, v = p.split("=", 1)
            fields[k.strip().lower()] = v.strip()
    title = clean_field(fields.get("title", ""))
    author = clean_field(
        fields.get("last") or fields.get("last1") or fields.get("author")
        or fields.get("vauthors") or fields.get("editor-last") or ""
    )
    venue = clean_field(
        fields.get("journal") or fields.get("newspaper") or fields.get("magazine")
        or fields.get("work") or fields.get("website") or fields.get("publisher") or ""
    )
    year = extract_year(fields)
    if not title or len(title) < 3:
        return None
    return {"kind": kind, "title": title, "author": author or None,
            "venue": venue or None, "year": year}


def extract_units(wikitext: str, page_title: str) -> list:
    units = []
    paras = [p for p in wikitext.split("\n\n") if len(p) > MIN_PARA_CHARS]
    for para in paras:
        stripped = para.strip()
        if stripped.startswith(("{{", "==", "*", "|", "!", ":")):
            continue
        matches = list(REF_ANY.finditer(para))
        if not (MIN_REFS <= len(matches) <= MAX_REFS):
            continue

        seen_keys = set()
        refs_parsed = []
        clean_ok = True
        for m in matches:
            s = m.group(0)
            if REF_SELF.match(s):
                clean_ok = False  # reused named ref -> ambiguous mapping
                break
            fm = REF_FULL.match(s)
            if not fm:
                clean_ok = False
                break
            name, content = fm.group(1), fm.group(2)
            key = name or f"anon{len(refs_parsed)}:{content[:30]}"
            if key in seen_keys:
                clean_ok = False
                break
            seen_keys.add(key)
            if not FULL_CITE_RE.search(content):
                clean_ok = False
                break
            parsed = parse_cite_fields(content)
            if parsed is None:
                clean_ok = False
                break
            refs_parsed.append(parsed)
        if not clean_ok or len(refs_parsed) != len(matches):
            continue

        clean_text = REF_ANY.sub("[CITE]", para)
        clean_text = strip_wiki_markup(clean_text)
        if clean_text.count("[CITE]") != len(refs_parsed):
            continue
        if len(clean_text) < MIN_PARA_CHARS:
            continue

        # de-duplicate on (title, year) -- distinct refs should look distinct
        seen_td = set()
        distinct_ok = True
        for r in refs_parsed:
            td = (r["title"].lower(), r["year"])
            if td in seen_td:
                distinct_ok = False
                break
            seen_td.add(td)
        if not distinct_ok:
            continue

        units.append({
            "page": page_title,
            "text": clean_text,
            "n_refs": len(refs_parsed),
            "refs": refs_parsed,
        })
    return units


def main():
    OUT_DIR.mkdir(parents=True, exist_ok=True)

    fetched_titles = set()
    if TITLES_PATH.exists():
        fetched_titles = set(json.loads(TITLES_PATH.read_text()))

    print("fetching category member titles...", file=sys.stderr)
    titles = []
    titles += fetch_category_titles("Category:Good_articles", MAX_ARTICLES_PER_CATEGORY)
    titles += fetch_category_titles("Category:Featured_articles", 500)
    titles = list(dict.fromkeys(titles))  # de-dup, preserve order
    random.Random(20260925).shuffle(titles)
    print(f"{len(titles)} candidate article titles", file=sys.stderr)

    n_units_total = 0
    with open(UNITS_PATH, "a", encoding="utf-8") as out_f:
        for i, title in enumerate(titles):
            if title in fetched_titles:
                continue
            try:
                wt = fetch_wikitext(title)
                _sleep()
                if wt is None:
                    fetched_titles.add(title)
                    continue
                units = extract_units(wt, title)
                for u in units:
                    out_f.write(json.dumps(u, ensure_ascii=False) + "\n")
                out_f.flush()
                n_units_total += len(units)
                fetched_titles.add(title)
                if i % 10 == 0:
                    TITLES_PATH.write_text(json.dumps(sorted(fetched_titles)))
                    print(f"[{i}/{len(titles)}] {title!r}: {len(units)} units "
                          f"(running total {n_units_total})", file=sys.stderr)
            except Exception as e:  # never let one article kill the run
                print(f"[{i}] {title!r}: unexpected error {type(e).__name__}: {e}",
                      file=sys.stderr)
                fetched_titles.add(title)
                continue
            if n_units_total >= 3500:
                print("reached target unit count, stopping early", file=sys.stderr)
                break

    TITLES_PATH.write_text(json.dumps(sorted(fetched_titles)))
    print(f"DONE: {n_units_total} total units written to {UNITS_PATH}", file=sys.stderr)


if __name__ == "__main__":
    main()
